export type Stance = 'orthodox' | 'southpaw';

export type AiArchetype =
  | 'volumeCombo'
  | 'counterSniper'
  | 'pressureBoxer'
  | 'legKickBrawler';

export interface FighterProfile {
  id: string;
  firstName: string;
  lastName: string;
  name: string;
  nickname: string;
  styleTag: string;
  weightClass: string;
  record: string;
  starRating: number; // e.g. 4.5 or 5
  isChampion?: boolean;
  stance: Stance;
  aiArchetype: AiArchetype;
  heightScale: number;
  buildScale: number;
  reachMeters: number;
  stats: {
    power: number; // 75 - 99
    speed: number; // 75 - 99
    chin: number; // 75 - 99
    cardio: number; // 75 - 99
    kickPower: number; // 75 - 99
  };
  appearance: {
    skinHex: string;
    hairHex: string;
    hairStyle: 'fade' | 'buzz' | 'textured' | 'shaved';
    facialHair: 'none' | 'stubble' | 'goatee' | 'fullBeard';
    shortsPrimaryHex: string;
    shortsAccentHex: string;
    shortsPattern: 'floral' | 'geometric' | 'tribal' | 'stripes' | 'stars';
    tattooStyle:
      | 'wings'
      | 'hollowayFull'
      | 'chestScript'
      | 'fullSleeveChest'
      | 'chestBand'
      | 'armSleeve'
      | 'tribalArm'
      | 'mcgregorChest'
      | 'poirierFull'
      | 'oliveiraChest'
      | 'omalleyChest'
      | 'minimal';
    chestHair?: boolean;
    hasLeftKneeSleeve: boolean;
    hasRightAnkleWrap: boolean;
    hasLeftAnkleWrap: boolean;
    tapeColor: 'red' | 'blue';
  };
}

