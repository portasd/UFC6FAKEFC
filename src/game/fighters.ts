export function matchesRosterFilter(
  fighter: FighterProfile,
  filter: RosterFilter,
): boolean {
  if (filter === 'all') return true;
  const wc = fighter.weightClass.toLowerCase();
  switch (filter) {
    case 'bantamweight':
      return wc.includes('bantamweight');
    case 'featherweight':
      return wc.includes('featherweight');
    case 'lightweight':
      return wc.startsWith('lightweight');
    case 'welterweight':
      return wc.includes('welterweight');
    case 'middleweight':
      return wc.includes('middleweight');
    case 'lightHeavyweight':
      return wc.includes('light heavyweight');
    case 'heavyweight':
      return wc.startsWith('heavyweight');
    case 'light':
      return (
        wc.includes('bantamweight') ||
        wc.includes('featherweight') ||
        wc.startsWith('lightweight')
      );
    case 'mid':
      return wc.includes('welterweight') || wc.includes('middleweight');
    case 'heavy':
      return wc.includes('light heavyweight') || wc.startsWith('heavyweight');
  }
}

