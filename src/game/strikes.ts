export type StrikeId =
  | 'jab'
  | 'cross'
  | 'leadHook'
  | 'rearHook'
  | 'overhand'
  | 'leadUppercut'
  | 'rearUppercut'
  | 'bodyHook'
  | 'rearBodyHook'
  | 'legKick'
  | 'rearLegKick'
  | 'bodyKick'
  | 'rearBodyKick'
  | 'leadHeadKick'
  | 'headKick'
  | 'spinningBackfist';

export type TargetZone = 'head' | 'body' | 'leg';

export interface StrikeSpec {
  id: StrikeId;
  label: string;
  zone: TargetZone;
  isKick: boolean;
  isLeadSide: boolean;
  windup: number; // seconds before active hit frame
  active: number; // active hitbox window
  recovery: number; // recovery duration
  cancelAt: number; // fraction of total duration after which next combo strike can chain
  reach: number; // meters
  baseDamage: number;
  blockChip: number;
  blockDrain: number;
  staminaCost: number;
  stunPower: number;
  hitstop: number; // seconds
  knockback: number;
  lungeSpeed: number; // forward momentum during strike
  comboNext: StrikeId[];
}

